import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  images: {
    /**
     * The widths the optimiser is allowed to emit, tuned to what this site
     * actually paints. Nothing here is wider than the footer scene at 980px,
     * so the 2048 and 3840 rungs of the default ladder only ever cost bytes:
     * a browser that asked for one got the full-size source back.
     *
     * The two extra rungs below 640 are the point of the exercise. A phone in
     * the three-up row is painted 195px wide, which at 2x wants 390px — and
     * the default ladder jumps 384 → 640, so every one of those rounded up to
     * a capture two-thirds larger than the frame it goes in. 448 and 576 land
     * on the sizes this site really asks for (195, 270 and 293px, at 1x-3x).
     * imageSizes must stay entirely below the smallest deviceSizes entry.
     */
    imageSizes: [32, 48, 64, 96, 128, 256, 384, 448, 576],
    deviceSizes: [640, 750, 828, 896, 1080, 1200, 1920],

    /**
     * The captures are already webp and regenerated by hand, so an optimised
     * variant stays correct until someone reruns the capture script. Holding
     * them for a month keeps the server from re-encoding a 1080x2190 screen
     * every four hours for a picture that has not changed. New captures reach
     * the optimiser under a new content hash, so this does not stale them.
     */
    minimumCacheTTL: 2_678_400, // 31 days
  },
};

export default nextConfig;
